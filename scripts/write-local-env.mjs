// Writes .env.local from the running LOCAL Supabase stack (`npm run db:start`).
// Only ever uses the local development keys; never point this at a real project.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const status = JSON.parse(execFileSync("npx", ["supabase", "status", "-o", "json"], { encoding: "utf8" }));
if (!/^http:\/\/(127\.0\.0\.1|localhost):/.test(status.API_URL)) {
  console.error(`Refusing: API_URL ${status.API_URL} is not a local stack.`);
  process.exit(1);
}
const values = {
  NEXT_PUBLIC_APP_URL: "http://localhost:3000",
  APP_ENV: "local",
  NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: status.PUBLISHABLE_KEY,
  SUPABASE_SECRET_KEY: status.SECRET_KEY,
  SUPABASE_DB_URL: status.DB_URL,
  // A fixed local value so tests can call /api/jobs/tick. Deployed environments set their own.
  CRON_SECRET: "local-only-cron-secret-0000",
};
let body = existsSync(".env.example") ? readFileSync(".env.example", "utf8") : "";
for (const [key, value] of Object.entries(values)) {
  const line = `${key}=${value}`;
  body = new RegExp(`^${key}=.*$`, "m").test(body)
    ? body.replace(new RegExp(`^${key}=.*$`, "m"), line)
    : `${body}\n${line}`;
}
writeFileSync(".env.local", "# Generated by `npm run env:local` from the local Supabase stack. Local only.\n" + body);
console.log("Wrote .env.local for the local stack.");
